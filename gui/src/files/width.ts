function isWide(cp: number): boolean {
  let lo = 0;
  let hi = WIDE.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [s, e] = WIDE[mid]!;
    if (cp < s) hi = mid - 1;
    else if (cp > e) lo = mid + 1;
    else return true;
  }
  return false;
}

/** 文字 ch（1 つの code point）を画面の桁 vis に置いたときの幅。 */
export function runeWidth(ch: string, vis: number): number {
  if (ch === "\t") return TAB_WIDTH - (vis % TAB_WIDTH);
  return isWide(ch.codePointAt(0) ?? 0) ? 2 : 1;
}
