// マウスの位置のマス目 → rune の位置の変換は shj（core）が同じ規則で行うので、ずれると押した場所と
// カーソルの位置が食い違う（設計書 docs/design/gui-protocol.md の 1 章と 3 章「入力」）。
//
// - タブは 4 桁ごとの位置まで進む。
// - 東アジアの全角（W・F）と絵文字は 2 桁。曖昧（A）は 1 桁（go-runewidth の既定と同じ）。
// - 幅 0 の文字（結合文字・制御文字）も 1 桁に数える（buffer.RuneWidth と同じ）。

/** タブの幅（shj の buffer.TabWidth）。 */
